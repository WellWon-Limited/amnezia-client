#!/usr/bin/env python3
# AVPN «Доступ к сайтам РФ», Android layer 1 (apps): writes the compiled list of Russian app packages from its
# maintained JSON into the two places that must agree - client/core/serviceEngine/ru_apps.h (the engine puts the
# installed ones into the session config as upstream's "exclude these apps") and the <queries> block of
# client/android/AndroidManifest.xml (package visibility on API 30+: without it every listed app reads as not
# installed). check_android_bypass_apps_wiring.sh fails when the two differ.
# Usage: python3 -I client/android/tools/gen_ru_apps.py <ru-apps.json>
# JSON: {"apps": [{"package": "...", "name": "...", "category": "..."}, ...], "never": [{"package": ...}, ...]}
# ("never" = browsers and anything that must stay in the tunnel; plain strings are accepted for packages too).
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # client/
HEADER = ROOT / "core/serviceEngine/ru_apps.h"
MANIFEST = ROOT / "android/AndroidManifest.xml"
OWN = "com.tribevpn.client"
PKG = re.compile(r"^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$")
BEGIN = "<!-- avpn-ru-apps-queries:begin -->"
END = "<!-- avpn-ru-apps-queries:end -->"


def packages(items):
    out = []
    for it in items or []:
        p = it if isinstance(it, str) else (it or {}).get("package", "")
        p = str(p).strip()
        if not PKG.match(p):
            sys.exit(f"not a package name: {p!r}")
        out.append(p)
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__ or "usage: gen_ru_apps.py <ru-apps.json>")
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    apps = sorted(set(packages(data.get("apps") or data.get("list") or [])))
    never = sorted(set(packages(data.get("never") or data.get("browsers") or [])))
    never_set = set(never) | {OWN}
    dropped = [p for p in apps if p in never_set]
    apps = [p for p in apps if p not in never_set]
    lines = [
        "// AVPN «Доступ к сайтам РФ», Android layer 1 (apps): Russian app packages the VPN service excludes from the",
        "// tunnel while the mode is on (VpnService.Builder.addDisallowedApplication - they use the network directly and see",
        "// no VPN); RU_APP_NEVER (browsers) is never excluded. GENERATED by client/android/tools/gen_ru_apps.py from the",
        "// maintained ru-apps.json, together with the <queries> block of client/android/AndroidManifest.xml - do not edit",
        "// by hand; rerun the script with the new JSON. Sorted, one package per line.",
        "#pragma once",
        "",
        "namespace avpn {",
        "",
        "inline const char *const RU_APP_PACKAGES[] = {",
    ]
    lines += [f'    "{p}",' for p in apps]
    lines += ["};", "", "inline const char *const RU_APP_NEVER[] = {"]
    lines += [f'    "{p}",' for p in never]
    lines += ["};", "", "} // namespace avpn", ""]
    HEADER.write_text("\n".join(lines), encoding="utf-8")

    m = MANIFEST.read_text(encoding="utf-8")
    block = [BEGIN, "    <queries>"] + [f'        <package android:name="{p}" />' for p in apps] + ["    </queries>", "    " + END]
    new_block = "\n".join(block)
    if BEGIN in m:
        m = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: new_block, m, flags=re.S)
    else:
        sys.exit("AndroidManifest.xml has no avpn-ru-apps-queries markers")
    MANIFEST.write_text(m, encoding="utf-8")
    print(f"ru_apps.h + manifest <queries>: {len(apps)} packages, {len(never)} never"
          + (f"; dropped from the list (never/own): {len(dropped)}" if dropped else ""))


if __name__ == "__main__":
    main()
