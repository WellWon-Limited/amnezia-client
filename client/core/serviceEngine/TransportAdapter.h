struct TransportOperationToken {
    // `operation` changes for every user/reconcile intent; `session` changes for every concrete
    // transport attempt inside that operation. Both are required so a late callback from an old
    // AWG/Xray core cannot stop or mark the replacement tunnel ready.
    quint64 operation = 0;
    quint64 session = 0;
    bool isValid() const { return operation != 0 && session != 0; }
    friend bool operator==(TransportOperationToken a, TransportOperationToken b)
    {
        return a.operation == b.operation && a.session == b.session;
    }
    friend bool operator!=(TransportOperationToken a, TransportOperationToken b)
    {
        return !(a == b);
    }
};

enum class TransportEventKind {
    TunnelReady = 0,
    StartRejected,
    RuntimeError,
    Stopped,
    // Authority renewal is a separate exact-session transaction.  Dispatch acknowledgement is
    // never success: only a durable native receipt may produce AuthorityRenewed.
    AuthorityRenewed,
    AuthorityRenewalRejected,
    AuthorityRenewalTimedOut,
};

