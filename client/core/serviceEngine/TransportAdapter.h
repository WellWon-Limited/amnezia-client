class ITransportAdapter {
public:
    virtual ~ITransportAdapter() = default;
    virtual TransportKind transport() const = 0;
    virtual amnezia::DockerContainer nativeContainer() const = 0;
    virtual QSet<QString> supportedProfileKinds() const = 0;

    // Must sanitize typed NativeProfile::config and compile through Amnezia's native model.
    // No adapter registered (or validation failure) means the candidate is unusable.
    virtual bool validateAndCompile(const CatalogCandidate &candidate,
                            CompiledNativeProfile &compiled,
                            QString &error) const = 0;
    // Preparation has zero native/TUN ownership. It snapshots and sanitizes all local policy so a
    // platform guard can establish the exact outer policy before any inner core starts.
    virtual bool prepareStart(const CompiledNativeProfile &compiled,
                              TransportOperationToken operation,
                              PreparedTransportStart &prepared,
                              QString &error) = 0;
    // All events must be delivered deferred/queued and echo the immutable operation token.
    virtual void setObserver(ITransportAdapterObserver *observer) = 0;
    // Detach only the expected owner; prevents a dying reducer from clearing a replacement owner.
    virtual void clearObserver(ITransportAdapterObserver *expected) = 0;
    // start/stop are reconcile-owner entry points and must not perform nested event loops or
    // synchronous network probes. Native readiness is reported later through the observer.
    // A false return, and a deferred StartRejected event, are a strict zero-ownership guarantee:
    // no TUN, routes, sockets, or native session may have been acquired. Once native ownership may
    // exist, failure is RuntimeError and the exact session must prove Stopped before fallback.
    virtual bool start(const PreparedTransportStart &prepared,
                       TransportOperationToken operation,
                       QString &error) = 0;
    // Refreshes only the signed runtime authority of the exact live native session. Implementations
    // must prove identical transport/profile/config+binding generations and dispatch-policy digest.
    // Unsupported platforms return RestartRequired; Rejected is a fail-closed security failure.
    virtual TransportAuthorityRenewalResult renewRuntimeAuthority(
        const CatalogCandidate &, const CatalogRuntimeAuthority &,
        TransportOperationToken, TransportAuthorityRenewalDispatch &dispatch,
        QString &error)
    {
        dispatch = {};
        error = QStringLiteral("native runtime authority renewal unavailable");
        return TransportAuthorityRenewalResult::RestartRequired;
    }
    virtual void stop(TransportOperationToken operation) = 0;
    virtual TransportTelemetry telemetry() const = 0;
};

class TransportAdapterRegistry {
public:
    bool add(ITransportAdapter *adapter, QString &error)
    {
        error.clear();
        if (!adapter || adapter->transport() == TransportKind::Unknown) {
            error = QStringLiteral("invalid transport adapter");
            return false;
        }
        if (adapter->nativeContainer() != nativeContainerForTransport(adapter->transport())) {
            error = QStringLiteral("adapter transport/native container mismatch");
            return false;
        }
        if (adapter->supportedProfileKinds().isEmpty()
            || adapter->supportedProfileKinds().contains(QString())) {
            error = QStringLiteral("adapter has no bounded profile-kind allowlist");
            return false;
        }
        const int key = static_cast<int>(adapter->transport());
        if (m_adapters.contains(key)) {
            error = QStringLiteral("duplicate transport adapter");
            return false;
        }
        m_adapters.insert(key, adapter);
        return true;
    }

    ITransportAdapter *adapter(TransportKind transport) const
    {
        return m_adapters.value(static_cast<int>(transport), nullptr);
    }

    bool compile(const CatalogCandidate &candidate, CompiledNativeProfile &compiled,
                 QString &error) const
    {
        compiled = CompiledNativeProfile{};
        error.clear();
        if (candidate.nativeProfile.profileKind != candidate.profileKind
            || candidate.nativeProfile.containerType
                   != nativeContainerTypeForTransport(candidate.transport)
            || candidate.nativeProfile.configGeneration == 0
            || candidate.nativeProfile.bindingGeneration == 0
            || candidate.nativeProfile.config.isEmpty()) {
            error = QStringLiteral("candidate/native envelope is inconsistent");
            return false;
        }
        ITransportAdapter *selected = adapter(candidate.transport);
        if (!selected) {
            error = QStringLiteral("no sanitizer/compiler registered for transport");
            return false;
        }
        if (!selected->supportedProfileKinds().contains(candidate.profileKind)) {
            error = QStringLiteral("adapter does not support profile kind");
            return false;
        }
        if (!selected->validateAndCompile(candidate, compiled, error))
            return false;
        if (compiled.container != nativeContainerForTransport(candidate.transport)) {
            compiled = CompiledNativeProfile{};
            error = QStringLiteral("compiled native container mismatch");
            return false;
        }
        if (!hasExpectedNativeEnvelope(compiled, candidate.transport)) {
            compiled = CompiledNativeProfile{};
            error = QStringLiteral("adapter returned malformed transport/native envelope");
            return false;
        }
        if (compiled.transport != candidate.transport || compiled.profileId != candidate.profileId
            || compiled.locationId != candidate.locationId
            || compiled.locationCountry != candidate.locationCountry
            || compiled.failureDomain != candidate.failureDomain
            || compiled.configGeneration != candidate.nativeProfile.configGeneration
            || compiled.bindingGeneration != candidate.nativeProfile.bindingGeneration
            || !compiled.expiresAt.isValid()
            || compiled.expiresAt.toUTC() != candidate.nativeProfile.expiresAt.toUTC()) {
            compiled = CompiledNativeProfile{};
            error = QStringLiteral("compiled native profile metadata mismatch");
            return false;
        }
        return true;
    }

private:
    QHash<int, ITransportAdapter *> m_adapters; // non-owning; app lifecycle owns adapters
};

